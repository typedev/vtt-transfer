"""VTT sources for an unhinted static font, from Microsoft's templates — what VTT's "Prepare Font" plus
"Control Program Only" do, without the closed autohinter:

- the standard font program (`templates/fpgmtmpl.txt`);
- the Control Program template (`templates/cvttmpl.txt`) with the heights and stems of `measure` written
  into its CVTs (each with a comment naming the glyphs it was measured on, or "not measured");
- character groups (TSI5) from `templates/chargrp.txt` by Unicode, unencoded glyphs by their base name,
  else by Unicode category;
- empty VTT Talk for every glyph, composites with VTT's component assembly (`OFFSET[R]`…).

The pre-program is generated by the compiler from the Control Program. Glyf instructions and the old
`fpgm`/`prep`/`cvt ` are dropped. Templates: github.com/microsoft/VisualTrueType (MIT), see
`templates/NOTICE.md`.
"""

from __future__ import annotations

import re
import unicodedata
from collections import Counter
from pathlib import Path

import vttcompilepy as vtt
from fontTools.ttLib import TTFont, newTable

from . import control
from . import measure as measure_mod
from .core import render_component

TEMPLATES = Path(__file__).parent / "templates"
SOURCE_TABLES = ("TSI0", "TSI1", "TSI2", "TSI3", "TSI5", "TSIC", "TSIB", "TSID", "TSIJ", "TSIP", "TSIS", "TSIV")
# TSI5 numbers of the standard groups (as VTT writes them)
GROUPS = {"OTHER": 1, "UPPERCASE": 2, "LOWERCASE": 3, "FIGURE": 4}
GROUP_NAMES = {v: k.capitalize() for k, v in GROUPS.items()}
FLAG_ROUND = 0x0004
FLAG_USE_MY_METRICS = 0x0200


class FreshError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code


def template(name: str) -> str:
    """A template as VTT keeps sources: no BOM, CR line ends."""
    text = (TEMPLATES / name).read_text(encoding="utf-8-sig")
    return re.sub(r"\r\n|\n", "\r", text)


def char_groups() -> tuple[dict[int, str], dict[str, str]]:
    """chargrp.txt → ({unicode: group}, {postscript name: group})."""
    by_code, by_name = {}, {}
    for line in (TEMPLATES / "chargrp.txt").read_text(encoding="utf-8-sig").splitlines():
        p = line.split()
        if len(p) >= 6 and p[0].startswith("0x") and p[4] in GROUPS:
            by_code.setdefault(int(p[0], 16), p[4])
            by_name.setdefault(p[5], p[4])
    return by_code, by_name


def assign_groups(font: TTFont) -> dict[str, int]:
    """TSI5 group of every glyph."""
    by_code, by_name = char_groups()
    cmap = font.getBestCmap() or {}
    codes: dict[str, int] = {}
    for code, name in sorted(cmap.items()):
        codes.setdefault(name, code)

    def of_code(code):
        if code in by_code:
            return by_code[code]
        cat = unicodedata.category(chr(code))
        return "UPPERCASE" if cat in ("Lu", "Lt") else "LOWERCASE" if cat == "Ll" else "FIGURE" if cat == "Nd" else "OTHER"

    def of_name(name, depth=0):
        if name in codes:
            return of_code(codes[name])
        if name in by_name:
            return by_name[name]
        base = re.split(r"[._]", name, maxsplit=1)[0]
        if depth < 2 and base and base != name:
            return of_name(base, depth + 1)
        m = re.fullmatch(r"(?:uni|u)([0-9A-Fa-f]{4,6})", base)
        return of_code(int(m.group(1), 16)) if m else "OTHER"

    return {name: GROUPS[of_name(name)] for name in font.getGlyphOrder()}


def control_program(measured: dict[int, measure_mod.Measured]) -> str:
    """The Control Program template with the measured values in its CVTs: `2: 690 /* cap height */
    /* measured: H E F … (17/17) */`. CVTs inside comments (the template's examples) are not CVTs;
    slots `measure` knows of but could not measure get 0 and a "not measured" comment."""
    src = template("cvttmpl.txt")
    defined = control.parse(src).cvts
    for num, meas in measured.items():
        if num not in defined:
            continue
        if meas.value is None:
            note = "not measured"
        elif meas.glyphs:
            note = f"measured: {' '.join(meas.glyphs[:8])}{' …' if len(meas.glyphs) > 8 else ''} ({meas.samples}/{meas.total})"
        else:
            note = f"= cvt {meas.parent}" if meas.parent is not None else ""
        # the first comment is the CVT's name (viewers show it as the label), the second the evidence
        src = control.set_cvt(src, num, value=meas.value if meas.value is not None else 0,
                              name=meas.what, note=note)
    return src


def composite_asm(font: TTFont, name: str, gids: dict[str, int]) -> str:
    g = font["glyf"][name]
    lines = [f"/* TT glyph {gids[name]}, char ({name}) */"]
    for c in g.components:
        prefixes = ["USEMYMETRICS"] if c.flags & FLAG_USE_MY_METRICS else []
        lines += render_component(prefixes, "R" if c.flags & FLAG_ROUND else "r", gids[c.glyphName], c)
    return "\r".join(lines)


def prepare(font: TTFont, measured: dict | None = None) -> tuple[TTFont, dict]:
    """VTT sources from the templates for an unhinted static, compiled. Returns the compiled font and a
    report {measured, groups}. The input font is changed in place (use a copy if you need it)."""
    if "fvar" in font:
        raise FreshError("vf", "variable fonts are not supported yet (CVT variations are needed)")
    if "TSI1" in font or "TSI3" in font:
        raise FreshError("has_sources", "the font already has VTT sources")
    if "glyf" not in font:
        raise FreshError("no_glyf", "not a TrueType-flavoured font")
    if measured is None:
        measured = measure_mod.measure(font)

    glyf = font["glyf"]
    order = font.getGlyphOrder()
    gids = {n: i for i, n in enumerate(order)}
    for name in order:
        glyf[name].removeHinting()
    for tag in ("fpgm", "prep", "cvt ", *SOURCE_TABLES):
        if tag in font:
            del font[tag]

    groups = assign_groups(font)
    tsi1, tsi3, tsi5 = newTable("TSI1"), newTable("TSI3"), newTable("TSI5")
    tsi1.glyphPrograms = {n: composite_asm(font, n, gids) if glyf[n].isComposite() else "" for n in order}
    tsi1.extraPrograms = {"fpgm": template("fpgmtmpl.txt"), "ppgm": "", "cvt": control_program(measured)}
    tsi3.glyphPrograms = {n: "" for n in order}
    tsi3.extraPrograms = {}
    tsi5.glyphGrouping = groups
    font["TSI0"], font["TSI1"], font["TSI2"], font["TSI3"], font["TSI5"] = newTable("TSI0"), tsi1, newTable("TSI2"), tsi3, tsi5

    c = vtt.Compiler.from_ttfont(font)
    c.compile_all()
    out = c.get_ttfont(vtt.StripLevel.STRIP_NOTHING)
    counts = Counter(GROUP_NAMES[g] for g in groups.values())
    return out, dict(measured=measure_mod.as_json(measured), groups=dict(counts))
